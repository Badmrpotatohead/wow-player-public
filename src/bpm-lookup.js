// ─── Local Cache ───────────────────────────────────────────────────────────

function loadLocalCache() {
  try { return JSON.parse(localStorage.getItem(LOCAL_CACHE_KEY) || "{}"); }
  catch { return {}; }
}

function saveLocalCache(cache) {
  try {
    const entries = Object.entries(cache);
    if (entries.length > 3000) cache = Object.fromEntries(entries.slice(-2000));
    localStorage.setItem(LOCAL_CACHE_KEY, JSON.stringify(cache));
  } catch {}
}

// ─── Proxy calls ───────────────────────────────────────────────────────────

async function proxyCall(body) {
  try {
    const resp = await fetch(BPM_PROXY, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify(body),
    });
    if (!resp.ok) {
      console.warn("BPM proxy error:", resp.status);
      return null;
    }
    return await resp.json();
  } catch (err) {
    console.warn("BPM proxy fetch error:", err.message);
    return null;
  }
}

async function getFromFirebase(key) {
  const result = await proxyCall({ action: "firebase-get", key });
  return result?.bpm || null;
}

async function saveToFirebase(key, bpm, title, artist, source) {
  proxyCall({ action: "firebase-set", key, bpm, title, artist, source });
}

async function searchGetSongBPM(title, artist) {
  const result = await proxyCall({ action: "search", title, artist });
  return result?.bpm || null;
}

// ─── Clean helpers ─────────────────────────────────────────────────────────

export function cleanTitle(title) {
  return title.toLowerCase()
    .replace(/\s*\(feat\..*?\)/gi, "").replace(/\s*\(ft\..*?\)/gi, "")
    .replace(/\s*\(with.*?\)/gi, "").replace(/\s*\(.*?remix.*?\)/gi, "")
    .replace(/\s*\(.*?remaster.*?\)/gi, "").replace(/\s*-\s*remaster(ed)?.*$/gi, "")
    .replace(/\s*-\s*radio edit.*$/gi, "").replace(/\s*-\s*stripped.*$/gi, "")
    .replace(/\s*-\s*acoustic.*$/gi, "").replace(/\s*-\s*live.*$/gi, "")
    .trim();
}

export function cleanArtist(artist) {
  return artist.toLowerCase().split(",")[0].split("&")[0].split(" and ")[0].trim();
}

export function firebaseKey(title, artist) {
  return `${title}|||${artist}`.toLowerCase().trim()
    .replace(/[.$#\[\]/]/g, "_")
    .replace(/\s+/g, "_")
    .substring(0, 200);
}

export function lookupInBuiltinDB(title, artist) {
  const ct = cleanTitle(title);
  const ca = cleanArtist(artist);
  for (const [key, bpm] of Object.entries(BUILTIN_DB)) {
    const [dbTitle, dbArtist] = key.split("|||");
    if (ct === dbTitle && ca === dbArtist) return bpm;
  }
  for (const [key, bpm] of Object.entries(BUILTIN_DB)) {
    const [dbTitle, dbArtist] = key.split("|||");
    if ((ct.includes(dbTitle) || dbTitle.includes(ct)) &&
        (ca.includes(dbArtist) || dbArtist.includes(ca))) return bpm;
  }
  return null;
}

// ─── AI Fallback (via proxy) ───────────────────────────────────────────────

async function lookupViaAI(title, artist) {
  const result = await proxyCall({
    action: "ai-lookup",
    title: cleanTitle(title),
    artist: cleanArtist(artist),
  });
  return result?.bpm || null;
}

// ─── Public API ────────────────────────────────────────────────────────────

// Normalize BPM for WCS range (60-140). Halve anything above 140.
export function wcsBpm(bpm) {
  if (!bpm) return bpm;
  return bpm > 140 ? Math.round(bpm / 2) : bpm;
}

// Cached lookups (not manual entries) are re-checked against the shared DB
// after this long, so approved community corrections reach every device.
const CACHE_REFRESH_MS = 7 * 24 * 60 * 60 * 1000;
const REFRESHABLE_SOURCES = new Set(["builtin", "firebase", "getsongbpm", "ai"]);

async function refreshFromFirebase(localKey, fbKey, cachedBpm) {
  const firebaseBpm = await getFromFirebase(fbKey);
  const cache = loadLocalCache();
  const current = cache[localKey];
  if (!current || typeof current !== "object" || !REFRESHABLE_SOURCES.has(current.source)) return;
  if (firebaseBpm && wcsBpm(firebaseBpm) !== cachedBpm) {
    cache[localKey] = { bpm: wcsBpm(firebaseBpm), source: "firebase", at: Date.now() };
  } else {
    cache[localKey] = { ...current, at: Date.now() };
  }
  saveLocalCache(cache);
}

export async function lookupBPM(_unused, title, artist) {
  if (!title) return null;

  const localCache = loadLocalCache();
  const fbKey = firebaseKey(cleanTitle(title), cleanArtist(artist));
  const localKey = `${title}|||${artist}`.toLowerCase().trim();

  // 1. Local cache (instant)
  if (localKey in localCache && localCache[localKey] !== null) {
    // Support both old format (number) and new format ({bpm, source, at})
    const cached = localCache[localKey];
    if (typeof cached !== "object") return cached;
    if (cached.bpm && REFRESHABLE_SOURCES.has(cached.source) &&
        !(cached.at > Date.now() - CACHE_REFRESH_MS)) {
      refreshFromFirebase(localKey, fbKey, cached.bpm);
    }
    return cached.bpm;
  }

  // 2. Firebase shared DB (via proxy) — checked before the built-in list so
  //    corrections made by DJs (and approved community submissions) win.
  const firebaseBpm = await getFromFirebase(fbKey);
  if (firebaseBpm) {
    const bpm = wcsBpm(firebaseBpm);
    console.log(`🔥 Firebase: "${title}" → ${bpm} BPM`);
    localCache[localKey] = { bpm, source: "firebase", at: Date.now() };
    saveLocalCache(localCache);
    return bpm;
  }

  // 3. Built-in database (5800+ WCS songs — no network)
  const builtinBpm = lookupInBuiltinDB(title, artist);
  if (builtinBpm) {
    const bpm = wcsBpm(builtinBpm);
    console.log(`📚 Built-in: "${title}" → ${bpm} BPM`);
    localCache[localKey] = { bpm, source: "builtin", at: Date.now() };
    saveLocalCache(localCache);
    return bpm;
  }

  // 4. GetSongBPM API (via proxy)
  const gsbBpm = await searchGetSongBPM(cleanTitle(title), cleanArtist(artist));
  if (gsbBpm) {
    const bpm = wcsBpm(gsbBpm);
    console.log(`🎵 GetSongBPM: "${title}" → ${bpm} BPM`);
    localCache[localKey] = { bpm, source: "getsongbpm", at: Date.now() };
    saveLocalCache(localCache);
    saveToFirebase(fbKey, bpm, cleanTitle(title), cleanArtist(artist), "getsongbpm");
    return bpm;
  }

  // 5. AI fallback
  console.log(`🤖 Trying AI for: "${title}" by "${artist}"...`);
  const aiBpm = await lookupViaAI(title, artist);
  if (aiBpm) {
    const bpm = wcsBpm(aiBpm);
    console.log(`🤖 AI estimate: "${title}" → ${bpm} BPM`);
    localCache[localKey] = { bpm, source: "ai", at: Date.now() };
    saveLocalCache(localCache);
    saveToFirebase(fbKey, bpm, cleanTitle(title), cleanArtist(artist), "ai-estimate");
    return bpm;
  }

  console.log(`❌ No BPM found for: "${title}" by "${artist}" — flagging for manual entry`);
  localCache[localKey] = { bpm: null, source: "manual_pending" };
  saveLocalCache(localCache);
  return null;
}

export async function setManualBPM(title, artist, bpm) {
  const localCache = loadLocalCache();
  const localKey = `${title}|||${artist}`.toLowerCase().trim();
  const fbKey = firebaseKey(cleanTitle(title), cleanArtist(artist));

  localCache[localKey] = { bpm, source: "manual" };
  saveLocalCache(localCache);
  await saveToFirebase(fbKey, bpm, cleanTitle(title), cleanArtist(artist), "manual");
}

export function clearBPMCache() {
  localStorage.removeItem(LOCAL_CACHE_KEY);
}
